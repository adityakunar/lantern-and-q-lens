#!/usr/bin/env python3
"""Build one network allowlist per note (skill), each in its own agent environment.

Each skill gets only its own hosts: every host in skills/<skill>/sources*.json (any "url" or
"base_url" value, at any depth) plus its sections of network/extra-hosts.txt ([news];
[all] goes to every skill). It writes environments/<env>.yml with networking:
limited, and skills/<skill>/allowed-hosts.txt, so the collector knows its list and reports a
blocked host clearly. The API allows 128 hosts per environment, so splitting by note keeps each
list well under the ceiling. Standard library only.

To approve a source that moved to another site: change its URL in the skill's sources file
(or add the host to network/extra-hosts.txt), rerun this script, ./sync-shared.sh, ant apply.

    python3 network/build-env.py           # rewrite the environment file
    python3 network/build-env.py --check   # exit 1 if the file is out of date (run before ant apply)
    python3 network/build-env.py --list    # print each environment's hosts and where each comes from

Run it from anywhere; paths are relative to the q-lens folder (this file's parent's parent).
"""
import argparse, json, re, sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
EXTRA = ROOT / "network" / "extra-hosts.txt"
# skill folder -> (environment name, extra-hosts.txt section). Add a line per note you add.
# A deployment points at its skill's environment in deployments/*.yml.
ENVS = {
    "curate-weekly": ("q-lens-env", "news"),
}
HOST_RE = re.compile(r"^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{0,62}$")

HEADER = """\
# yaml-language-server: $schema=https://platform.claude.com/schemas/ant/beta/environment.json
# GENERATED by network/build-env.py from skills/{skill}/sources*.json and network/extra-hosts.txt [{section}], [all].
# Do not edit by hand: change the sources or extra-hosts.txt, then rerun the script.
#
# Limited network: the sandbox, web_fetch and web_search reach only the hosts below, which are
# the {skill} skill's own. Package registries and MCP servers stay blocked.
name: {name}
metadata: {}
scope: organization
config:
  type: cloud
  networking:
    type: limited
    allow_package_managers: false
    allow_mcp_servers: false
    allowed_hosts:
"""


def urls_in(node):
    if isinstance(node, dict):
        for key, value in node.items():
            if key in ("url", "base_url") and isinstance(value, str):
                yield value
            else:
                yield from urls_in(value)
    elif isinstance(node, list):
        for value in node:
            yield from urls_in(value)


# The API accepts at most 128 allowed hosts. Hosts are exact (no automatic www/bare twins, which
# doubled the list): a site that redirects to its twin gets that host in extra-hosts.txt.
MAX_HOSTS = 128
WARN_AT = 110


def collect(skill, section_name):
    """Hosts for one skill: its own sources files plus its extra-hosts.txt sections."""
    found, problems = {}, []
    for path in sorted(ROOT.glob(f"skills/{skill}/sources*.json")):
        label = path.relative_to(ROOT).as_posix()
        try:
            data = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError) as exc:
            problems.append(f"{label}: cannot read ({exc})")
            continue
        for url in urls_in(data):
            parts = urlsplit(url)
            host = (parts.hostname or "").lower()
            if parts.scheme not in ("http", "https") or not HOST_RE.match(host):
                problems.append(f"{label}: skipped URL without a usable host: {url}")
                continue
            found.setdefault(host, set()).add(label)
    if EXTRA.exists():
        section = None
        for n, raw in enumerate(EXTRA.read_text().splitlines(), 1):
            line = raw.split("#", 1)[0].strip().lower()
            if not line:
                continue
            if line.startswith("["):
                section = re.split(r"[\]:\s]", line[1:], maxsplit=1)[0]
                if section not in {s for _, s in ENVS.values()} | {"all"}:
                    problems.append(f"extra-hosts.txt line {n}: unknown section [{section}] "
                                    f"(use news or all)")
                continue
            if section not in (section_name, "all"):
                continue
            if not HOST_RE.match(line):
                problems.append(f"extra-hosts.txt line {n}: not a bare hostname: {raw.strip()}")
                continue
            found.setdefault(line, set()).add(f"extra-hosts.txt [{section}]")
    return found, problems


def render(hosts, skill, name, section):
    head = HEADER.replace("{skill}", skill).replace("{name}", name).replace("{section}", section)
    return head + "".join(f"      - {h}\n" for h in sorted(hosts))


def render_list(hosts, name):
    return (f"# GENERATED by network/build-env.py: the hosts environment {name} allows. Do not edit.\n"
            + "".join(f"{h}\n" for h in sorted(hosts)))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if any environment file is out of date")
    ap.add_argument("--list", action="store_true", help="print each host and where it comes from")
    args = ap.parse_args()

    stale, failed, warned = [], False, set()
    for skill, (name, section) in ENVS.items():
        if not (ROOT / "skills" / skill / "SKILL.md").exists():
            print(f"warning: skills/{skill} not found; skipping {name}", file=sys.stderr)
            continue
        found, problems = collect(skill, section)
        for p in problems:
            if p not in warned:
                warned.add(p)
                print("warning:", p, file=sys.stderr)
        if not found:
            print(f"{name}: no hosts found for skills/{skill}", file=sys.stderr)
            failed = True
            continue
        if len(found) > MAX_HOSTS:
            print(f"{name}: {len(found)} hosts is over the API limit of {MAX_HOSTS}. Remove sources "
                  f"or extra-hosts.txt entries (see --list). Nothing was written for it.", file=sys.stderr)
            failed = True
            continue
        if len(found) > WARN_AT:
            print(f"warning: {name}: {len(found)} of {MAX_HOSTS} allowed hosts used; little room left",
                  file=sys.stderr)

        if args.list:
            print(f"== {name} (skills/{skill}): {len(found)} hosts")
            for h in sorted(found):
                print(f"  {h:40} {', '.join(sorted(found[h]))}")
            continue

        env_file = ROOT / "environments" / f"{name}.yml"
        list_file = ROOT / "skills" / skill / "allowed-hosts.txt"
        text, listing = render(found, skill, name, section), render_list(found, name)
        current = env_file.read_text() if env_file.exists() else ""
        current_list = list_file.read_text() if list_file.exists() else ""
        if args.check:
            stale += [f.relative_to(ROOT).as_posix() for f, new, old in
                      ((env_file, text, current), (list_file, listing, current_list)) if new != old]
            continue
        if current_list != listing:
            list_file.write_text(listing)
            print(f"wrote {list_file.relative_to(ROOT)}")
        if current == text:
            print(f"{name}: unchanged, {len(found)} hosts")
            continue
        old = set(re.findall(r"^      - (\S+)$", current, re.M))
        env_file.parent.mkdir(exist_ok=True)
        env_file.write_text(text)
        print(f"wrote {env_file.relative_to(ROOT)}: {len(found)} hosts")
        if old:
            print("  added:  ", " ".join(sorted(set(found) - old)) or "-")
            print("  removed:", " ".join(sorted(old - set(found))) or "-")

    if args.check:
        if stale:
            print(f"out of date: {', '.join(stale)} (run python3 network/build-env.py)")
            sys.exit(1)
        print("up to date")
    if failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
